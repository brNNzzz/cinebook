/**
 * Função global que retorna avaliações exclusivas e personalizadas para a obra
 */
function getCuratedReviewsForMedia(item) {
  if (!item) return [];

  // Obras que ainda não foram lançadas não podem ter avaliações de quem já
  // assistiu/leu — nem as "exclusivas" cadastradas aqui, nem as geradas
  // automaticamente. A camada de UI também esconde a seção inteira, mas essa
  // trava fica aqui como segunda barreira caso a função seja chamada direto.
  if (item.notReleasedYet) return [];

  const id = String(item.id || '').toLowerCase();
  const tmdbId = String(item.tmdbId || '');
  const title = (item.title || '').toLowerCase();

  // 1. Busca por ID direto no catálogo de avaliações exclusivas
  if (SPECIFIC_REVIEWS_CATALOG[id]) {
    return SPECIFIC_REVIEWS_CATALOG[id];
  }
  // 2. Busca por tmdbId
  if (tmdbId && SPECIFIC_REVIEWS_CATALOG[tmdbId]) {
    return SPECIFIC_REVIEWS_CATALOG[tmdbId];
  }

  // 3. Busca por correspondência de título ou palavras-chave
  for (const [k, revList] of Object.entries(SPECIFIC_REVIEWS_CATALOG)) {
    if (k.startsWith('m_') || k.startsWith('s_') || k.startsWith('b_')) {
      const slug = k.replace(/^[msb]_2026_|^[msb]_/, '');
      if (slug && title.includes(slug)) {
        return revList;
      }
    }
  }

  if (title.includes('duna') || title.includes('dune')) return SPECIFIC_REVIEWS_CATALOG['m1'];
  if (title.includes('interestelar') || title.includes('interstellar')) return SPECIFIC_REVIEWS_CATALOG['m2'];
  if (title.includes('oppenheimer')) return SPECIFIC_REVIEWS_CATALOG['m3'];
  if (title.includes('matrix')) return SPECIFIC_REVIEWS_CATALOG['m4'];
  if (title.includes('aranha') || title.includes('spider')) return SPECIFIC_REVIEWS_CATALOG['m5'];
  if (title.includes('origem') || title.includes('inception')) return SPECIFIC_REVIEWS_CATALOG['m6'];
  if (title.includes('blade runner')) return SPECIFIC_REVIEWS_CATALOG['m7'];
  if (title.includes('chefão') || title.includes('godfather')) return SPECIFIC_REVIEWS_CATALOG['m8'];
  if (title.includes('batman') || title.includes('cavaleiro das trevas')) return SPECIFIC_REVIEWS_CATALOG['m9'];
  if (title.includes('pulp fiction')) return SPECIFIC_REVIEWS_CATALOG['m10'];
  if (title.includes('last of us')) return SPECIFIC_REVIEWS_CATALOG['s1'];
  if (title.includes('breaking bad')) return SPECIFIC_REVIEWS_CATALOG['s2'];
  if (title.includes('stranger things')) return SPECIFIC_REVIEWS_CATALOG['s3'];
  if (title.includes('x-men')) return SPECIFIC_REVIEWS_CATALOG['s4'];
  if (title.includes('xógum') || title.includes('shogun') || title.includes('shōgun')) return SPECIFIC_REVIEWS_CATALOG['s5'];
  if (title.includes('arcane')) return SPECIFIC_REVIEWS_CATALOG['s6'];
  if (title.includes('silo')) return SPECIFIC_REVIEWS_CATALOG['s7'];
  if (title.includes('ruptura') || title.includes('severance')) return SPECIFIC_REVIEWS_CATALOG['s8'];
  if (title.includes('1984')) return SPECIFIC_REVIEWS_CATALOG['b2'];
  if (title.includes('senhor dos anéis') || title.includes('lord of the rings')) return SPECIFIC_REVIEWS_CATALOG['b3'];
  if (title.includes('três corpos') || title.includes('three-body')) return SPECIFIC_REVIEWS_CATALOG['b4'];
  if (title.includes('neuromancer')) return SPECIFIC_REVIEWS_CATALOG['b5'];
  if (title.includes('fahrenheit')) return SPECIFIC_REVIEWS_CATALOG['b6'];
  if (title.includes('fundação') || title.includes('foundation')) return SPECIFIC_REVIEWS_CATALOG['b7'];
  if (title.includes('casmurro')) return SPECIFIC_REVIEWS_CATALOG['b8'];
  if (title.includes('hobbit')) return SPECIFIC_REVIEWS_CATALOG['b9'];
  if (title.includes('admirável mundo novo') || title.includes('brave new world')) return SPECIFIC_REVIEWS_CATALOG['b10'];

  // 4. Se for qualquer outro filme/série do catálogo ou TMDb, gera dinamicamente com base nas características da obra
  return generateProceduralReviewsForMedia(item);
}
