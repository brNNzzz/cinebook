/**
 * Retorna o título traduzido de qualquer obra de acordo com o idioma ativo
 */
function getMediaTitle(item, targetLang = null) {
  if (!item) return '';
  const currentL = targetLang || (typeof localStorage !== 'undefined' ? localStorage.getItem('cinebook_lang') : 'pt') || 'pt';
  
  if (currentL === 'pt') {
    return item.baseTitle || item.title || item.originalTitle || '';
  }

  const itemId = String(item.id || '');
  const tmdbId = String(item.tmdbId || '');

  // 1. Busca no Catálogo Central de Traduções
  if (typeof MEDIA_TRANSLATIONS_CATALOG !== 'undefined') {
    const tr = MEDIA_TRANSLATIONS_CATALOG[itemId] || MEDIA_TRANSLATIONS_CATALOG[tmdbId];
    if (tr) {
      if (tr[currentL]?.title) return tr[currentL].title;
      if (tr['en']?.title) return tr['en'].title;
    }
  }

  // 2. Busca na propriedade translations do próprio objeto
  if (item.translations) {
    if (item.translations[currentL]?.title) return item.translations[currentL].title;
    if (item.translations['en']?.title) return item.translations['en'].title;
  }

  if (item.localizedTitles) {
    if (item.localizedTitles[currentL]) return item.localizedTitles[currentL];
    if (item.localizedTitles['en']) return item.localizedTitles['en'];
  }

  // 3. Fallback inteligente: se for em inglês ou idioma não-PT e tiver originalTitle internacional, usa originalTitle
  if (item.originalTitle && item.originalTitle.trim() && item.originalTitle !== item.title) {
    return item.originalTitle;
  }

  return item.title || item.originalTitle || '';
}

