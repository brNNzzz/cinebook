let currentLang = localStorage.getItem('cinebook_lang') || 'pt';

/**
 * Retorna uma tradução por chave
 */
function t(key) {
  const langDict = I18N_DICTIONARY[currentLang] || I18N_DICTIONARY.pt;
  return langDict[key] || key;
}

/**
 * Atualiza o idioma e traduz todos os elementos da página
 */
function setLanguage(lang) {
  if (!I18N_DICTIONARY[lang]) return;
  currentLang = lang;
  localStorage.setItem('cinebook_lang', lang);

  // Suporte a direção de texto RTL para Árabe e Urdu
  if (lang === 'ar' || lang === 'ur') {
    document.documentElement.setAttribute('dir', 'rtl');
  } else {
    document.documentElement.removeAttribute('dir');
  }

  // Atualiza atributo lang do documento
  document.documentElement.lang = lang;

  // Traduz elementos com data-i18n (texto interno)
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N_DICTIONARY[lang][key]) {
      el.textContent = I18N_DICTIONARY[lang][key];
    }
  });

  // Traduz elementos com data-i18n-html (HTML interno)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (I18N_DICTIONARY[lang][key]) {
      el.innerHTML = I18N_DICTIONARY[lang][key];
    }
  });

  // Traduz placeholders com data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (I18N_DICTIONARY[lang][key]) {
      el.placeholder = I18N_DICTIONARY[lang][key];
    }
  });

  // Traduz atributos title com data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (I18N_DICTIONARY[lang][key]) {
      el.title = I18N_DICTIONARY[lang][key];
    }
  });

  // Atualiza o Badge do Idioma no Header
  const langBadgeText = document.getElementById('currentLangText');
  const langBadgeFlag = document.getElementById('currentLangFlag');
  const currentLangObj = SUPPORTED_LANGUAGES.find(l => l.code === lang) || SUPPORTED_LANGUAGES[0];

  if (langBadgeText) langBadgeText.textContent = currentLangObj.short || I18N_DICTIONARY[lang]?.lang_name || 'PT';
  if (langBadgeFlag) {
    langBadgeFlag.innerHTML = getLanguageFlagHtml(currentLangObj.country, currentLangObj.name, currentLangObj.flag);
  }

  // Atualiza estado ativo e ícone check no dropdown
  document.querySelectorAll('.lang-option-item').forEach(item => {
    const isCur = item.getAttribute('data-lang') === lang;
    item.classList.toggle('active', isCur);
    const existingCheck = item.querySelector('.lang-check-icon');
    if (isCur && !existingCheck) {
      const check = document.createElement('span');
      check.className = 'lang-check-icon';
      check.textContent = '✓';
      item.appendChild(check);
    } else if (!isCur && existingCheck) {
      existingCheck.remove();
    }
  });

  // Notifica componentes dinâmicos (como o grid em app.js)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

/**
 * Retorna o HTML do ícone da bandeira com suporte a CDN HD e fallback gracioso
 */
function getLanguageFlagHtml(countryCode, altName, fallbackEmoji = '🌐') {
  return `<img src="https://flagcdn.com/w40/${countryCode.toLowerCase()}.png" srcset="https://flagcdn.com/w80/${countryCode.toLowerCase()}.png 2x" alt="${altName}" class="lang-flag-img" loading="lazy" onerror="this.onerror=null; this.parentElement.textContent='${fallbackEmoji}';" />`;
}

/**
 * Renderiza dinamicamente a lista de 11 idiomas no dropdown com ícones de bandeiras
 */
function renderLanguageDropdownOptions() {
  const dropdown = document.getElementById('langDropdownMenu');
  if (!dropdown) return;

  dropdown.innerHTML = '';
  SUPPORTED_LANGUAGES.forEach(l => {
    const item = document.createElement('div');
    const isActive = l.code === currentLang;
    item.className = `lang-option-item ${isActive ? 'active' : ''}`;
    item.setAttribute('data-lang', l.code);
    item.innerHTML = `
      <span class="lang-flag-box">${getLanguageFlagHtml(l.country, l.name, l.flag)}</span>
      <span class="lang-option-name">${l.name}</span>
      ${isActive ? '<span class="lang-check-icon">✓</span>' : ''}
    `;
    item.addEventListener('click', () => {
      setLanguage(l.code);
      dropdown.classList.remove('open');
    });
    dropdown.appendChild(item);
  });
}

/**
 * Inicializa o Seletor de Idiomas Dropdown
 */
function initLanguageDropdown() {
  const trigger = document.getElementById('langSelectorTrigger');
  const dropdown = document.getElementById('langDropdownMenu');

  if (!trigger || !dropdown) return;

  renderLanguageDropdownOptions();

  // Toggle do dropdown
  trigger.addEventListener('click', (e) => {
    e.stopPropagation();
    dropdown.classList.toggle('open');
  });

  // Fechar ao clicar fora
  document.addEventListener('click', (e) => {
    if (!trigger.contains(e.target) && !dropdown.contains(e.target)) {
      dropdown.classList.remove('open');
    }
  });
}

// Inicializa no carregamento do DOM
document.addEventListener('DOMContentLoaded', () => {
  initLanguageDropdown();
  setLanguage(currentLang);
});
